import assert from "node:assert/strict";
import { existsSync,readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const source=read("lib/lead-message.ts");
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const sandbox={exports:{}};vm.runInNewContext(js,sandbox,{timeout:2000});
const {cleanLeadField,parseLeadInterest,buildLeadMessage,whatsappHref}=sandbox.exports;
assert.equal(cleanLeadField(" Juan \n Otro "), "Juan Otro");
assert.equal(cleanLeadField("a".repeat(150),80).length,80);
assert.equal(parseLeadInterest("curso"),"curso");
assert.equal(parseLeadInterest("webinar"),"clases");
assert.equal(parseLeadInterest("__proto__"),"clases");
const msg=buildLeadMessage({nombre:"Javier \n Otro: falso",interes:"curso",nivel:"Preuniversitario",tema:"Funciones",detalle:"Necesito dominio\nPregunta inyectada"});
assert.match(msg,/Nombre: Javier Otro: falso/);
assert.match(msg,/Consulta: Necesito dominio Pregunta inyectada/);
assert.doesNotMatch(msg,/utm_source|utm_campaign|Origen:/);
assert.match(whatsappHref(msg),/^https:\/\/wa\.me\/51925475034\?text=/);
assert.equal(decodeURIComponent(whatsappHref(msg).split("?text=")[1]),msg);
const form=read("components/conversion.tsx");
assert.match(form,/setDraft\(\{message,url:whatsappHref\(message\)/);
assert.match(form,/className="lead-whatsapp-link"/);
assert.match(form,/lead_message_preview/);
assert.match(form,/lead_whatsapp_click/);
assert.match(form,/onChange=\{\(\)=>setDraft\(null\)\}/);
assert.doesNotMatch(form,/window\.open|setSent\(|lead_whatsapp_submit/);
assert.doesNotMatch(form,/track\([^)]*,\s*\{[^}]*\b(?:nombre|detalle|message)\s*:/);
const contact=read("app/contacto/page.tsx");
assert.match(contact,/id="contactar"/);
assert.match(contact,/Hablemos de tu aprendizaje/);
assert.match(read("app/conversion-trust.css"),/body:has\(\.contact-page-v2\) \.conversion-dock/);
assert.equal((contact.match(/<ConversionForm\/>/g)||[]).length,1);
assert.ok(contact.indexOf("<ConversionForm/>")<contact.indexOf("public-contact-steps"));
assert.match(read("app/privacidad/page.tsx"),/WhatsApp puede procesar/);
assert.match(read("components/funnel.tsx"),/try\{window\.sessionStorage\.setItem/);
assert.doesNotMatch(read("app/empieza/page.tsx"),/utm_source=tiktok/);
assert.doesNotMatch(read("app/clase/funciones-antes-de-calculo/page.tsx"),/utm_source=youtube/);
assert.match(read("components/site.tsx"),/href="\/privacidad"/);
assert.match(read("app/layout.tsx"),/import "\.\/conversion-trust\.css"/);
assert.doesNotMatch(read("app/layout.tsx"),/latitude: -12\.046374|solucionario oficial/);
assert.ok(existsSync(new URL("../app/conversion-trust.css",import.meta.url)));
const offer=read("app/cursos/funciones-para-calculo/page.tsx");
assert.match(offer,/Precio de referencia/);
assert.doesNotMatch(offer,/LISTA PRIORITARIA ABIERTA|primeros 30|4 sesiones grupales|Acceso al contenido durante 12 meses/);
assert.match(offer,/Las condiciones de inscripción se confirman/);
assert.match(offer,/Materiales complementarios previstos/);
assert.doesNotMatch(read("components/blog-constructor-explorer.tsx"),/Simulador con clave oficial verificada/);
console.log("✓ Capa 06: formulario, datos, atribución, transparencia comercial y rutas de contacto validados.");
